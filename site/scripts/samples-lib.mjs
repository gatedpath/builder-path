import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { samples, projectRoot } from '../samples.config.mjs';

export const siteDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const rootDir = resolve(siteDir, projectRoot);
export const generatedDir = resolve(siteDir, 'src/samples/generated');
export const publicDir = resolve(siteDir, 'public');

export const sha256 = (s) => createHash('sha256').update(s).digest('hex');

const extFor = (lang, source) => {
  const known = { solidity: 'sol', toml: 'toml', ts: 'ts', js: 'js', md: 'md', json: 'json', txt: 'txt' };
  return known[lang] ?? source.split('.').pop();
};

/** Cut the region a sample names out of its source text. Whole file when no anchors. */
export function extract(sample, text) {
  if (!sample.from) return text;
  const lines = text.split('\n');
  const start = lines.findIndex((l) => l.includes(sample.from));
  if (start < 0) throw new Error(`${sample.id}: start anchor not found in ${sample.source}: ${sample.from}`);
  let end = lines.findIndex((l, i) => i >= start && l.includes(sample.to));
  if (end < 0) throw new Error(`${sample.id}: end anchor not found in ${sample.source}: ${sample.to}`);
  if (sample.closeWith) {
    const close = lines.findIndex((l, i) => i > end && l === sample.closeWith);
    if (close < 0) throw new Error(`${sample.id}: closing line not found: ${sample.closeWith}`);
    end = close;
  }
  return lines.slice(Math.max(0, start - (sample.before ?? 0)), end + 1).join('\n') + '\n';
}

/** Read every configured source and return what the generated folder should contain. */
export function computeExpected() {
  const out = [];
  for (const s of samples) {
    const sourcePath = resolve(rootDir, s.source);
    const text = readFileSync(sourcePath, 'utf8');
    const content = extract(s, text);
    out.push({
      ...s,
      file: `${s.id}.${extFor(s.lang, s.source)}`,
      content,
      sourceSha256: sha256(text),
      sampleSha256: sha256(content),
      lines: content.split('\n').length - 1,
      whole: !s.from,
      fullText: text,
    });
  }
  return out;
}

export function manifestFor(expected) {
  return {
    note: 'Generated by scripts/extract-samples.mjs from samples.config.mjs. Do not edit; run `npm run samples`.',
    samples: expected.map(({ id, source, file, lang, title, compiledBy, from, to, sourceSha256, sampleSha256, lines, whole, publish }) => ({
      id, source, file, lang, title, compiledBy, region: from ? { from, to } : null, whole, lines, sourceSha256, sampleSha256, publish: publish ?? null,
    })),
  };
}
