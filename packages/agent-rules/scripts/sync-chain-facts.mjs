// Writes src/chain-facts.ts from the built @gatedpath/chains package. That package
// is canonical; this file is a snapshot so agent-rules keeps zero runtime dependencies.
// The unit tests fail if the snapshot and the package disagree.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { snapshotFromChains } from './snapshot.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const chains = await import(resolve(here, '..', '..', 'chain-definitions', 'dist', 'esm', 'index.js'));
const facts = snapshotFromChains(chains);

const body = JSON.stringify(facts, null, 2).replace(/^/gm, '');
const out = `// GENERATED by scripts/sync-chain-facts.mjs from @gatedpath/chains
// (packages/chain-definitions). That package is canonical: every address and URL here
// traces to its src/addresses.ts and src/chains.ts, and through them to RESEARCH.md.
// Do not edit by hand. Run \`npm run sync\` and commit the result.

export const chainFacts = ${body} as const;

export type ChainFacts = typeof chainFacts;
`;
writeFileSync(resolve(here, '..', 'src', 'chain-facts.ts'), out);
console.log('wrote src/chain-facts.ts');
